// Writes spec/x402-arl-upto/v0.1.0/vectors.json from the reference implementation
// (packages/payments). Run from the repository root:
//
//   node packages/payments/scripts/generate-spec-vectors.ts [--check]
//
// --check compares instead of writing and fails if vectors.json is out of date. The receipt
// signer is Anvil's first development key, which is public; it must never hold value.

import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";

import { privateKeyToAccount } from "viem/accounts";

import { meter } from "../src/metering.ts";
import {
  InMemoryAuthorizationStore,
  authorizationKey,
  decideSettlement,
  type Permit2Authorization,
} from "../src/policy.ts";
import {
  buildUsageReceipt,
  checkUsageReceipt,
  receiptToJson,
  signUsageReceipt,
} from "../src/receipt.ts";

const OUT = new URL("../../../spec/x402-arl-upto/v0.1.0/vectors.json", import.meta.url);
const CHAIN_ID = 84_532;
const DEV_KEY = "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80";
const signer = privateKeyToAccount(DEV_KEY);

const auth: Permit2Authorization = {
  from: "0x70997970C51812dc3A010C7d01b50e0d17dc79C8",
  spender: "0x4020A4f3b7b90ccA423B9fabCc0CE57C6C240002",
  nonce: "42",
  deadline: "1792900300",
  permitted: { token: "0x244312b619127B6458154F3467eFD7c87CD28500", amount: "1000000000000000000" },
  witness: {
    to: "0x3C44CdDdB6a900fa2b585dd299e03d12FA4293BC",
    facilitator: "0x90F79bf6EB2c4f870365E785982E1f101E93b906",
    validAfter: "0",
  },
};
const NOW = 1_792_900_000;
const response = new TextEncoder().encode('{"output":"passed=3 failed=0"}');

const meterVectors = [
  { unitPrice: "1000000000000000", units: "250", ceiling: "1000000000000000000" },
  { unitPrice: "1000000000000000", units: "2000", ceiling: "1000000000000000000" },
  { unitPrice: "0", units: "5", ceiling: "1" },
].map((v) => {
  const r = meter({
    unitPrice: BigInt(v.unitPrice),
    units: BigInt(v.units),
    ceiling: BigInt(v.ceiling),
  });
  return { input: v, amount: r.amount.toString(), capped: r.capped };
});

const decide = async (
  amount: bigint,
  mutate: (a: Permit2Authorization) => Permit2Authorization,
  used?: string,
) => {
  const store = new InMemoryAuthorizationStore();
  const a = mutate(structuredClone(auth));
  if (used) {
    await store.claim(authorizationKey(CHAIN_ID, a), "settling");
    await store.finish(authorizationKey(CHAIN_ID, a), used as "settled");
  }
  const d = await decideSettlement({ chainId: CHAIN_ID, auth: a, amount, nowSeconds: NOW, store });
  return {
    authorization: a,
    amount: amount.toString(),
    nowSeconds: NOW,
    previousState: used ?? null,
    decision:
      d.action === "settle" ? { action: d.action, key: d.key, amount: d.amount.toString() } : d,
  };
};
const same = (a: Permit2Authorization) => a;
const settlementVectors = [
  await decide(250_000_000_000_000_000n, same),
  await decide(0n, same),
  await decide(2_000_000_000_000_000_000n, same),
  await decide(1n, (a) => ({ ...a, deadline: String(NOW) })),
  await decide(1n, (a) => ({ ...a, deadline: String(NOW + 601) })),
  await decide(1n, same, "settled"),
];

const receipt = buildUsageReceipt({
  auth,
  resource: "job?seconds=60",
  units: 250n,
  unitPrice: 1_000_000_000_000_000n,
  response,
});
const signed = await signUsageReceipt(signer, CHAIN_ID, receipt);
const tamper = (field: string, value: string) => ({
  receipt: { ...signed.receipt, [field]: value },
  signature: signed.signature,
});
const receiptCases: { name: string; signed: unknown; amount: bigint }[] = [
  { name: "valid", signed, amount: receipt.amount },
  {
    name: "amount raised after signing",
    signed: tamper("amount", "300000000000000000"),
    amount: 300_000_000_000_000_000n,
  },
  { name: "settled amount differs from the receipt", signed, amount: 300_000_000_000_000_000n },
  {
    name: "different response bytes",
    signed: tamper("response", `0x${"11".repeat(32)}`),
    amount: receipt.amount,
  },
];
const receiptVectors = await Promise.all(
  receiptCases.map(async (c) => ({
    name: c.name,
    signed: c.signed,
    signer: signer.address,
    authorization: auth,
    amount: c.amount.toString(),
    responseUtf8: new TextDecoder().decode(response),
    problems: await checkUsageReceipt({
      chainId: CHAIN_ID,
      signed: c.signed,
      signer: signer.address,
      auth,
      amount: c.amount,
      response,
    }),
  })),
);

const vectors = {
  spec: "x402-arl-upto",
  version: "0.1.0",
  chainId: CHAIN_ID,
  note: "Generated by generate-vectors.ts from packages/payments. The signer is a public development key.",
  receiptDomain: { name: "ARL Usage Receipt", version: "1", chainId: CHAIN_ID },
  meter: meterVectors,
  settlement: settlementVectors,
  receipt: { unsigned: receiptToJson(receipt), cases: receiptVectors },
};
const text = `${JSON.stringify(vectors, null, 2)}\n`;
if (process.argv.includes("--check")) {
  if (JSON.stringify(JSON.parse(readFileSync(OUT, "utf8"))) !== JSON.stringify(vectors)) {
    process.stderr.write("vectors.json is out of date: run generate-spec-vectors.ts\n");
    process.exit(1);
  }
  process.stdout.write("vectors.json matches the reference implementation\n");
} else {
  writeFileSync(OUT, text);
  process.stdout.write("wrote vectors.json\n");
}
