// Writes contracts/baseMainnetContracts.ts from the Foundry build and the Base Mainnet records:
// every ARL contract the app uses on Base Mainnet, with its ABI and the block it was deployed in
// (history reads start there).
//
// - ARLToken, ARLVestingWallet (the investors' wallet): docs/mainnet-plan.md (2026-10-24)
// - ARLJobs (the ARL escrow): contracts/deploy/base-mainnet-jobs.json
// - ARLStakingRewards: contracts/deploy/base-mainnet-services.json
//
//   node scripts/generate-mainnet-contracts.ts [--check]
//
// --check compares instead of writing, and fails if the committed file is out of date.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contractsDir = join(here, "..", "..", "..", "contracts");
const check = process.argv.includes("--check");
const outPath = join(here, "..", "contracts", "baseMainnetContracts.ts");

const read = <T>(path: string): T => JSON.parse(readFileSync(path, "utf8")) as T;
const token = {
  chainId: 8_453,
  token: "0xde91E6f39D50bBd875f831dcc1134A3D7f3aaDb4",
  investorsVesting: "0x8E2CC3a5F39038836475650f63A91d107BabA643",
};
const jobs = read<{ chainId: number; arl: { jobs: string } }>(
  join(contractsDir, "deploy", "base-mainnet-jobs.json"),
);
const services = read<{ chainId: number; staking: string }>(
  join(contractsDir, "deploy", "base-mainnet-services.json"),
);
for (const r of [token, jobs, services]) {
  if (r.chainId !== 8_453) throw new Error("a Base Mainnet record names another chain");
}

// Deployment blocks, read on chain (the first block with code at each address).
const CONTRACTS = {
  ARLToken: { address: token.token, deployedOnBlock: 53_023_206 },
  ARLVestingWallet: { address: token.investorsVesting, deployedOnBlock: 53_023_098 },
  ARLStakingRewards: { address: services.staking, deployedOnBlock: 56_649_904 },
  ARLJobs: { address: jobs.arl.jobs, deployedOnBlock: 53_315_381 },
} as const;

const abi = (name: string): unknown =>
  read<{ abi: unknown }>(join(contractsDir, "out", `${name}.sol`, `${name}.json`)).abi;

function normalise(text: string): string {
  return text
    .replace(/\s+/g, "")
    .replace(/,([}\]])/g, "$1")
    .replace(/"(\w+)":/g, "$1:");
}

const contracts = Object.fromEntries(
  Object.entries(CONTRACTS).map(([name, c]) => [
    name,
    { address: c.address, abi: abi(name), deployedOnBlock: c.deployedOnBlock },
  ]),
);
const body = `{\n  8453: ${JSON.stringify(contracts, null, 2).replace(/\n/g, "\n  ")},\n}`;

const source = `/**
 * Generated by scripts/generate-mainnet-contracts.ts from the Foundry build and the Base Mainnet
 * records (contracts/deploy). Do not edit by hand.
 */
const baseMainnetContracts = ${body} as const;

export default baseMainnetContracts;
`;
if (check) {
  if (normalise(readFileSync(outPath, "utf8")) !== normalise(source)) {
    console.error(`${outPath} is out of date: run node scripts/generate-mainnet-contracts.ts`);
    process.exit(1);
  }
  console.log("baseMainnetContracts.ts matches the Base Mainnet records");
} else {
  writeFileSync(outPath, source);
  console.log(`wrote ${outPath} (format it with prettier)`);
}
